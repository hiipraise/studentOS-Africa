"use client";

import Link from "next/link";
import { useState } from "react";
import { Sparkles, ArrowRight, Share2, BookmarkPlus, Check, Copy, Loader2, Info } from "lucide-react";
import { DeadlineBadge } from "@/components/shared/DeadlineBadge";
import type { FinderResult } from "@/types";

interface FinderResultsProps {
  result: FinderResult;
  onReset: () => void;
}

export function FinderResults({ result, onReset }: FinderResultsProps) {
  const { picks, explanation, considered, ai, note, shareUrl } = result;
  const [saveState, setSaveState] = useState<"idle" | "saving" | "saved" | "error">("idle");
  const [copied, setCopied] = useState(false);

  async function saveAll() {
    setSaveState("saving");
    try {
      const response = await fetch("/api/saved", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ items: picks.map((pick) => ({ slug: pick.slug, title: pick.title, deadline: pick.deadline })) }),
      });
      if (response.status === 401) {
        setSaveState("error");
        return;
      }
      setSaveState(response.ok ? "saved" : "error");
    } catch {
      setSaveState("error");
    }
  }

  async function copyShare() {
    if (!shareUrl) return;
    try {
      await navigator.clipboard.writeText(shareUrl);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      setCopied(false);
    }
  }

  return (
    <div className="flex flex-col gap-8">
      <div className="rounded-2xl bg-forest/5 border border-forest/15 p-5 flex gap-3">
        <Sparkles className="h-5 w-5 text-forest shrink-0 mt-0.5" aria-hidden="true" />
        <div className="flex flex-col gap-1">
          <p className="text-sm text-ink/80 leading-relaxed">{explanation}</p>
          <p className="text-xs text-muted">
            {ai ? "Explanations generated by AI from a compact candidate set." : "Ranked deterministically — no AI required."} {considered} {considered === 1 ? "candidate" : "candidates"} matched your filters.
          </p>
        </div>
      </div>

      {note && (
        <p className="flex items-start gap-2 rounded-lg bg-sage px-4 py-3 text-xs text-ink/70">
          <Info className="h-4 w-4 shrink-0 mt-0.5" aria-hidden="true" /> {note}
        </p>
      )}

      {picks.length === 0 ? (
        <p className="text-sm text-muted text-center py-8">No strong matches found yet — try broadening your field or interests.</p>
      ) : (
        <section className="flex flex-col gap-3">
          <h2 className="text-lg font-semibold text-ink">Your matches</h2>
          <div className="flex flex-col gap-3">
            {picks.map((pick) => (
              <article key={pick.slug} className="card-base flex flex-col gap-2.5">
                <div className="flex items-start justify-between gap-3">
                  <div className="min-w-0">
                    <span className="text-xs font-medium text-forest">{pick.category}</span>
                    <h3 className="font-semibold text-ink text-[15px] leading-snug">
                      <Link href={`/opportunities/${pick.slug}`} className="no-underline hover:text-forest">{pick.title}</Link>
                    </h3>
                  </div>
                  <DeadlineBadge deadline={pick.deadline} />
                </div>
                <p className="text-sm text-ink/75 leading-relaxed">{pick.reason}</p>
                {pick.matchedCriteria.length > 0 && (
                  <ul className="flex flex-wrap gap-1.5">
                    {pick.matchedCriteria.map((criterion) => (
                      <li key={criterion} className="rounded-full bg-sage px-2.5 py-0.5 text-[11px] font-medium text-forest">{criterion}</li>
                    ))}
                  </ul>
                )}
                <Link href={`/opportunities/${pick.slug}`} className="inline-flex items-center gap-1 text-xs font-semibold text-forest">
                  View details <ArrowRight className="h-3.5 w-3.5" aria-hidden="true" />
                </Link>
              </article>
            ))}
          </div>
        </section>
      )}

      <div className="flex flex-wrap items-center justify-center gap-3">
        {picks.length > 0 && (
          <button onClick={saveAll} disabled={saveState === "saving"} className="btn-ghost border border-border rounded-lg px-4 py-2.5 text-sm inline-flex items-center gap-2">
            {saveState === "saving" ? <Loader2 className="h-4 w-4 animate-spin" /> : saveState === "saved" ? <Check className="h-4 w-4 text-forest" /> : <BookmarkPlus className="h-4 w-4" />}
            {saveState === "saved" ? "Saved to your list" : saveState === "error" ? "Sign in to save" : "Save these"}
          </button>
        )}
        {shareUrl && (
          <button onClick={copyShare} className="btn-ghost border border-border rounded-lg px-4 py-2.5 text-sm inline-flex items-center gap-2">
            {copied ? <Check className="h-4 w-4 text-forest" /> : <Copy className="h-4 w-4" />} {copied ? "Link copied" : "Copy share link"}
          </button>
        )}
        {shareUrl && (
          <a href={`https://wa.me/?text=${encodeURIComponent(`My StudentOS matches: ${shareUrl}`)}`} target="_blank" rel="noopener noreferrer" className="btn-ghost border border-border rounded-lg px-4 py-2.5 text-sm inline-flex items-center gap-2">
            <Share2 className="h-4 w-4" /> WhatsApp
          </a>
        )}
        <button onClick={onReset} className="btn-ghost border border-border rounded-lg self-center px-5 py-2.5 text-sm">Search again</button>
      </div>
    </div>
  );
}
